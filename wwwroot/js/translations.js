// ── Translation engine ───────────────────────────────────────────────────────

var _changedNodes = [];

var SKIP_TAGS = { SCRIPT: 1, STYLE: 1, INPUT: 1, TEXTAREA: 1, SVG: 1, CANVAS: 1 };

function _walkTranslate(node, dict) {
    if (node.nodeType === 3) { // TEXT_NODE
        var raw = node.textContent;
        var text = raw.trim();
        if (text && dict[text]) {
            _changedNodes.push({ node: node, orig: raw });
            node.textContent = raw.replace(text, dict[text]);
        }
    } else if (node.nodeType === 1 && !SKIP_TAGS[node.tagName]) {
        if (node.hasAttribute('data-i18n-en')) return; // already handled by layout system
        for (var i = 0; i < node.childNodes.length; i++) {
            _walkTranslate(node.childNodes[i], dict);
        }
    }
}

function translatePageContent(lang) {
    var content = document.querySelector('.page-content');
    if (!content) return;

    if (lang === 'en') {
        _changedNodes = [];
        _walkTranslate(content, window.PAGE_TRANSLATIONS);

        // Translate placeholders
        content.querySelectorAll('[placeholder]').forEach(function (el) {
            var ph = el.getAttribute('placeholder').trim();
            if (window.PAGE_TRANSLATIONS[ph] && !el.hasAttribute('data-ph-orig')) {
                el.setAttribute('data-ph-orig', el.getAttribute('placeholder'));
                el.setAttribute('placeholder', window.PAGE_TRANSLATIONS[ph]);
            }
        });

        // Translate select options
        content.querySelectorAll('option').forEach(function (el) {
            var text = el.textContent.trim();
            if (window.PAGE_TRANSLATIONS[text] && !el.hasAttribute('data-opt-orig')) {
                el.setAttribute('data-opt-orig', el.textContent);
                el.textContent = window.PAGE_TRANSLATIONS[text];
            }
        });

    } else {
        // Restore original Arabic text nodes
        for (var i = _changedNodes.length - 1; i >= 0; i--) {
            _changedNodes[i].node.textContent = _changedNodes[i].orig;
        }
        _changedNodes = [];

        // Restore placeholders
        content.querySelectorAll('[data-ph-orig]').forEach(function (el) {
            el.setAttribute('placeholder', el.getAttribute('data-ph-orig'));
            el.removeAttribute('data-ph-orig');
        });

        // Restore select options
        content.querySelectorAll('[data-opt-orig]').forEach(function (el) {
            el.textContent = el.getAttribute('data-opt-orig');
            el.removeAttribute('data-opt-orig');
        });
    }
}
